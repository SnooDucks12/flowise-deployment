#!/usr/bin/env node
/* ============================================================
   Wanderlight manifest generator
   ------------------------------------------------------------
   Scans ./photos/<YYYY-MM Trip Name>/ folders and rewrites
   photos.js so the gallery picks up your images automatically.

   Usage:
     node generate-manifest.js

   Folder layout example:
     photos/
       2024-06 Amalfi Coast/
         boat-day.jpg
         gelato.jpg
       2025-01 Lapland/
         aurora.jpg

   Captions come from filenames: "boat-day.jpg" → "boat day".
   To fine-tune captions/notes afterwards, edit photos.js by hand
   (re-running this script will overwrite manual edits).
   ============================================================ */
const fs = require("fs");
const path = require("path");

const ROOT = __dirname;
const PHOTOS_DIR = path.join(ROOT, "photos");
const OUT = path.join(ROOT, "photos.js");
const IMG_EXT = new Set([".jpg", ".jpeg", ".png", ".webp", ".gif", ".avif"]);

const MONTHS = ["", "Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];

// Preserve TOGETHER_SINCE from the existing manifest if present
let since = "2023-06-01";
try {
  const prev = fs.readFileSync(OUT, "utf8");
  const m = prev.match(/TOGETHER_SINCE\s*=\s*"([^"]+)"/);
  if (m) since = m[1];
} catch {}

if (!fs.existsSync(PHOTOS_DIR)) {
  console.error("No ./photos folder found. Create it, add trip folders, and re-run.");
  process.exit(1);
}

const trips = fs.readdirSync(PHOTOS_DIR, { withFileTypes: true })
  .filter((d) => d.isDirectory())
  .sort((a, b) => b.name.localeCompare(a.name)) // newest first
  .map((dir) => {
    const m = dir.name.match(/^(\d{4})-(\d{2})\s+(.+)$/);
    const title = m ? m[3] : dir.name;
    const date = m ? `${MONTHS[parseInt(m[2], 10)] || m[2]} ${m[1]}` : "";
    const id = title.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
    const photos = fs.readdirSync(path.join(PHOTOS_DIR, dir.name))
      .filter((f) => IMG_EXT.has(path.extname(f).toLowerCase()))
      .sort()
      .map((f) => ({
        src: `photos/${dir.name}/${f}`,
        caption: path.basename(f, path.extname(f)).replace(/[-_]+/g, " ").trim(),
      }));
    return { id, title, location: title, date, note: "", photos };
  })
  .filter((t) => t.photos.length > 0);

if (trips.length === 0) {
  console.error("Found ./photos but no images inside trip folders. Nothing written.");
  process.exit(1);
}

const body = `/* Auto-generated by generate-manifest.js — ${trips.length} trip(s).
   Edit captions/notes freely; re-running the script overwrites this file. */

window.TOGETHER_SINCE = ${JSON.stringify(since)};

window.TRIPS = ${JSON.stringify(trips, null, 2)};
`;

fs.writeFileSync(OUT, body);
console.log(`Wrote photos.js — ${trips.length} trips, ${trips.reduce((n, t) => n + t.photos.length, 0)} photos.`);
